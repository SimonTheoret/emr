use eyre::{Result, bail};
use http::{HeaderMap, HeaderName, Uri};
use url::Url;

const HOP_BY_HOP_HEADERS: &[&str] = &[
    "connection",
    "keep-alive",
    "proxy-authenticate",
    "proxy-authorization",
    "proxy-connection",
    "te",
    "trailer",
    "transfer-encoding",
    "upgrade",
];

/// Parse and validate the HTTP(S) base URL used for upstream requests.
pub(crate) fn parse_destination(value: &str) -> Result<Url> {
    let destination = Url::parse(value)?;

    if !matches!(destination.scheme(), "http" | "https") {
        bail!("destination must use the http or https scheme");
    }
    if destination.cannot_be_a_base() || destination.host().is_none() {
        bail!("destination must be an absolute URL with a host");
    }
    if destination.query().is_some() || destination.fragment().is_some() {
        bail!("destination must not contain a query or fragment");
    }

    Ok(destination)
}

/// Prefix an incoming origin-form path with the destination's base path.
pub(crate) fn upstream_url(destination: &Url, uri: &Uri) -> Result<Url> {
    let incoming_path = uri.path();
    if !incoming_path.starts_with('/') {
        bail!("incoming request URI must contain an origin-form path");
    }

    let base_path = destination.path().trim_end_matches('/');
    let joined_path = if base_path.is_empty() {
        incoming_path.to_owned()
    } else {
        format!("{base_path}{incoming_path}")
    };

    let mut upstream = destination.clone();
    upstream.set_path(&joined_path);
    upstream.set_query(uri.query());
    Ok(upstream)
}

/// Remove headers that apply only to one transport hop.
///
/// The caller supplies a clone when it also needs to retain the decoded wire
/// headers for recording.
pub(crate) fn sanitize_headers(headers: &mut HeaderMap) {
    let connection_headers: Vec<HeaderName> = headers
        .get_all("connection")
        .iter()
        .flat_map(|value| value.as_bytes().split(|byte| *byte == b','))
        .filter_map(|name| {
            let name = trim_ascii_whitespace(name);
            HeaderName::from_bytes(name).ok()
        })
        .collect();

    for name in connection_headers {
        headers.remove(name);
    }
    for name in HOP_BY_HOP_HEADERS {
        headers.remove(*name);
    }

    // These fields describe the adjacent connection or its framing and are
    // regenerated by reqwest/hyper for the next hop.
    headers.remove("host");
    headers.remove("content-length");
}

fn trim_ascii_whitespace(mut value: &[u8]) -> &[u8] {
    while value.first().is_some_and(u8::is_ascii_whitespace) {
        value = &value[1..];
    }
    while value.last().is_some_and(u8::is_ascii_whitespace) {
        value = &value[..value.len() - 1];
    }
    value
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_http_and_https_destinations_with_base_paths() {
        assert_eq!(
            parse_destination("http://example.test/api")
                .unwrap()
                .as_str(),
            "http://example.test/api"
        );
        assert_eq!(
            parse_destination("https://example.test:8443/api/")
                .unwrap()
                .as_str(),
            "https://example.test:8443/api/"
        );
    }

    #[test]
    fn rejects_invalid_destination_shapes() {
        for destination in [
            "ftp://example.test/api",
            "https://example.test/api?q=value",
            "https://example.test/api#fragment",
            "/relative/path",
        ] {
            assert!(parse_destination(destination).is_err(), "{destination}");
        }
    }

    #[test]
    fn prefixes_paths_and_preserves_the_incoming_query() {
        let destination = parse_destination("https://example.test:8443/api/").unwrap();
        let uri = "/v1/a%2Fb?tag=one&tag=&encoded=%2F".parse().unwrap();

        let upstream = upstream_url(&destination, &uri).unwrap();

        assert_eq!(
            upstream.as_str(),
            "https://example.test:8443/api/v1/a%2Fb?tag=one&tag=&encoded=%2F"
        );
    }

    #[test]
    fn handles_root_destination_and_request_paths() {
        let root = parse_destination("http://example.test/").unwrap();
        assert_eq!(
            upstream_url(&root, &"/resource".parse().unwrap())
                .unwrap()
                .as_str(),
            "http://example.test/resource"
        );

        let prefixed = parse_destination("http://example.test/api").unwrap();
        assert_eq!(
            upstream_url(&prefixed, &"/".parse().unwrap())
                .unwrap()
                .as_str(),
            "http://example.test/api/"
        );
    }

    #[test]
    fn strips_fixed_and_connection_nominated_headers() {
        let mut headers = HeaderMap::new();
        headers.append("connection", "keep-alive, x-remove-one".parse().unwrap());
        headers.append("connection", "x-remove-two".parse().unwrap());
        headers.insert("keep-alive", "timeout=5".parse().unwrap());
        headers.insert("proxy-authenticate", "Basic".parse().unwrap());
        headers.insert("proxy-authorization", "Basic abc".parse().unwrap());
        headers.insert("proxy-connection", "close".parse().unwrap());
        headers.insert("te", "trailers".parse().unwrap());
        headers.insert("trailer", "x-checksum".parse().unwrap());
        headers.insert("transfer-encoding", "chunked".parse().unwrap());
        headers.insert("upgrade", "websocket".parse().unwrap());
        headers.insert("x-remove-one", "one".parse().unwrap());
        headers.insert("x-remove-two", "two".parse().unwrap());
        headers.insert("host", "client.test".parse().unwrap());
        headers.insert("content-length", "12".parse().unwrap());

        sanitize_headers(&mut headers);

        assert!(headers.is_empty());
    }

    #[test]
    fn preserves_end_to_end_and_forwarding_metadata_headers() {
        let mut headers = HeaderMap::new();
        headers.append("x-end-to-end", "first".parse().unwrap());
        headers.append("x-end-to-end", "second".parse().unwrap());
        headers.insert("forwarded", "for=192.0.2.1".parse().unwrap());
        headers.insert("via", "1.1 proxy.test".parse().unwrap());
        headers.insert("x-forwarded-for", "192.0.2.1".parse().unwrap());

        sanitize_headers(&mut headers);

        assert_eq!(headers.get_all("x-end-to-end").iter().count(), 2);
        assert!(headers.contains_key("forwarded"));
        assert!(headers.contains_key("via"));
        assert!(headers.contains_key("x-forwarded-for"));
    }

    #[test]
    fn sanitizing_a_clone_does_not_change_recorded_headers() {
        let mut recorded = HeaderMap::new();
        recorded.insert("connection", "x-secret".parse().unwrap());
        recorded.insert("x-secret", "value".parse().unwrap());
        let mut forwarded = recorded.clone();

        sanitize_headers(&mut forwarded);

        assert!(forwarded.is_empty());
        assert_eq!(recorded["x-secret"], "value");
    }
}
