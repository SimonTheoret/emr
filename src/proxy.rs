use axum::{body::Body, response::Response};
use http::{HeaderMap, HeaderName, HeaderValue, StatusCode};
use url::{Position, Url};

use crate::ir::{UriIR, UrlIR};

const HOP_BY_HOP_HEADERS: &[&str] = &[
    "connection",
    "keep-alive",
    "proxy-authenticate",
    "proxy-authorization",
    "proxy-connection",
    "te",
    "trailer",
    "transfer-encoding",
    "upgrade",
];

/// Prefix an incoming origin-form path with the destination's base path.
pub(crate) fn upstream_url(destination: &UrlIR, uri: &UriIR) -> UrlIR {
    let mut upstream: UrlIR = destination.clone();
    let mut path: String = destination.path().trim_end_matches('/').to_owned();
    path.push_str(uri.path());
    upstream.set_path(&path);
    upstream.set_query(uri.query());
    upstream
}

/// The `Location` ERM sends its client for a redirect: the path that `upstream_url` forwards to
/// the URL `location` names. `None` if that URL is outside `destination`.
pub(crate) fn client_location(
    destination: &Url,
    requested: &Url,
    location: &HeaderValue,
) -> Option<HeaderValue> {
    let target = requested
        .join(std::str::from_utf8(location.as_bytes()).ok()?)
        .ok()?;
    if target.origin() != destination.origin() {
        return None;
    }
    let rest = target
        .path()
        .strip_prefix(destination.path().trim_end_matches('/'))?;
    if !(rest.is_empty() || rest.starts_with('/')) {
        return None;
    }
    let path = if rest.is_empty() { "/" } else { rest };
    HeaderValue::try_from(format!("{path}{}", &target[Position::AfterPath..])).ok()
}

/// Remove headers that apply only to one transport hop.
///
/// The caller supplies a clone when it also needs to retain the decoded wire
/// headers for recording.
pub(crate) fn sanitize_headers(headers: &mut HeaderMap) {
    let connection_headers: Vec<HeaderName> = headers
        .get_all("connection")
        .iter()
        .flat_map(|value| value.as_bytes().split(|byte| *byte == b','))
        .filter_map(|name| {
            let name = trim_ascii_whitespace(name);
            HeaderName::from_bytes(name).ok()
        })
        .collect();

    for name in connection_headers {
        headers.remove(name);
    }
    for name in HOP_BY_HOP_HEADERS {
        headers.remove(*name);
    }

    // These fields describe the adjacent connection or its framing and are
    // regenerated by reqwest/hyper for the next hop.
    headers.remove("host");
    headers.remove("content-length");
}

/// The response ERM sends its client, in both modes: a status, the headers after
/// `sanitize_headers`, and a streamed body. The connection to the client picks the version.
pub(crate) fn client_response(status: StatusCode, mut headers: HeaderMap, body: Body) -> Response {
    sanitize_headers(&mut headers);
    let mut response = Response::new(body);
    *response.status_mut() = status;
    *response.headers_mut() = headers;
    response
}

fn trim_ascii_whitespace(mut value: &[u8]) -> &[u8] {
    while value.first().is_some_and(u8::is_ascii_whitespace) {
        value = &value[1..];
    }
    while value.last().is_some_and(u8::is_ascii_whitespace) {
        value = &value[..value.len() - 1];
    }
    value
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn prefixes_paths_and_preserves_the_incoming_query() {
        let destination = "https://example.test:8443/api/".parse::<UrlIR>().unwrap();
        let uri = "/v1/a%2Fb?tag=one&tag=&encoded=%2F".parse().unwrap();

        let upstream = upstream_url(&destination, &uri);

        assert_eq!(
            upstream.as_str(),
            "https://example.test:8443/api/v1/a%2Fb?tag=one&tag=&encoded=%2F"
        );
    }

    #[test]
    fn handles_root_destination_and_request_paths() {
        let root = "http://example.test/".parse::<UrlIR>().unwrap();
        assert_eq!(
            upstream_url(&root, &"/resource".parse().unwrap()).as_str(),
            "http://example.test/resource"
        );

        let prefixed = "http://example.test/api".parse::<UrlIR>().unwrap();
        assert_eq!(
            upstream_url(&prefixed, &"/".parse().unwrap()).as_str(),
            "http://example.test/api/"
        );
    }

    fn client_location_of(location: &str) -> Option<String> {
        let destination = "http://up.test/api".parse().unwrap();
        let requested = "http://up.test/api/auth/start?step=1".parse().unwrap();
        client_location(
            &destination,
            &requested,
            &HeaderValue::from_str(location).unwrap(),
        )
        .map(|value| value.to_str().unwrap().to_owned())
    }

    #[test]
    fn a_location_inside_the_destination_becomes_a_path_erm_forwards_to_it() {
        let destination: UrlIR = "http://up.test/api".parse().unwrap();
        let requested: Url = "http://up.test/api/auth/start?step=1".parse().unwrap();
        for (location, rewritten) in [
            ("http://up.test/api/v2/login?next=%2F", "/v2/login?next=%2F"),
            ("HTTP://UP.test:80/api/v2/login", "/v2/login"),
            ("/api/v2/login", "/v2/login"),
            ("login", "/auth/login"),
            ("../login", "/login"),
            ("?step=2", "/auth/start?step=2"),
        ] {
            assert_eq!(
                client_location_of(location).as_deref(),
                Some(rewritten),
                "{location}"
            );
            assert_eq!(
                upstream_url(&destination, &rewritten.parse().unwrap()).as_str(),
                requested.join(location).unwrap().as_str(),
                "ERM forwards {rewritten} to the URL that {location} names"
            );
        }
        assert_eq!(
            client_location_of("/api/v2/login#form").as_deref(),
            Some("/v2/login#form"),
            "the fragment is kept"
        );
        assert_eq!(
            client_location_of("/api").as_deref(),
            Some("/"),
            "the destination itself is the root path"
        );
    }

    #[test]
    fn a_location_outside_the_destination_has_no_client_location() {
        for location in [
            "https://up.test/api/v2/login",
            "http://up.test:8080/api/v2/login",
            "http://other.test/api/v2/login",
            "//other.test/api/v2/login",
            "/v2/login",
            "/apix",
            "http://[::1",
        ] {
            assert_eq!(client_location_of(location), None, "{location}");
        }
    }

    #[test]
    fn strips_fixed_and_connection_nominated_headers() {
        let mut headers = HeaderMap::new();
        headers.append("connection", "keep-alive, x-remove-one".parse().unwrap());
        headers.append("connection", "x-remove-two".parse().unwrap());
        headers.insert("keep-alive", "timeout=5".parse().unwrap());
        headers.insert("proxy-authenticate", "Basic".parse().unwrap());
        headers.insert("proxy-authorization", "Basic abc".parse().unwrap());
        headers.insert("proxy-connection", "close".parse().unwrap());
        headers.insert("te", "trailers".parse().unwrap());
        headers.insert("trailer", "x-checksum".parse().unwrap());
        headers.insert("transfer-encoding", "chunked".parse().unwrap());
        headers.insert("upgrade", "websocket".parse().unwrap());
        headers.insert("x-remove-one", "one".parse().unwrap());
        headers.insert("x-remove-two", "two".parse().unwrap());
        headers.insert("host", "client.test".parse().unwrap());
        headers.insert("content-length", "12".parse().unwrap());

        sanitize_headers(&mut headers);

        assert!(headers.is_empty());
    }

    #[test]
    fn preserves_end_to_end_and_forwarding_metadata_headers() {
        let mut headers = HeaderMap::new();
        headers.append("x-end-to-end", "first".parse().unwrap());
        headers.append("x-end-to-end", "second".parse().unwrap());
        headers.insert("forwarded", "for=192.0.2.1".parse().unwrap());
        headers.insert("via", "1.1 proxy.test".parse().unwrap());
        headers.insert("x-forwarded-for", "192.0.2.1".parse().unwrap());

        sanitize_headers(&mut headers);

        assert_eq!(headers.get_all("x-end-to-end").iter().count(), 2);
        assert!(headers.contains_key("forwarded"));
        assert!(headers.contains_key("via"));
        assert!(headers.contains_key("x-forwarded-for"));
    }

    #[test]
    fn sanitizing_a_clone_does_not_change_recorded_headers() {
        let mut recorded = HeaderMap::new();
        recorded.insert("connection", "x-secret".parse().unwrap());
        recorded.insert("x-secret", "value".parse().unwrap());
        let mut forwarded = recorded.clone();

        sanitize_headers(&mut forwarded);

        assert!(forwarded.is_empty());
        assert_eq!(recorded["x-secret"], "value");
    }
}
